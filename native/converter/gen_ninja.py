#!/usr/bin/env python3
"""Generate a ninja build file that compiles the subset of OCCT 7.6.3 needed by
u3dconv and links the converter as a fully static musl executable.

Usage:
  gen_ninja.py --src <occt>/src --build <dir> --inc <flat include dir>
               --cxx <c++ wrapper> --ar <ar wrapper> --main <converter src dir>
               [--target aarch64|x86_64] [--out <binary path>] [--jobs-hint N]

The generated build.ninja has one static library per toolkit (libTKxxx.a) and
one link edge for the final executable.
"""
import argparse
import glob
import os
import sys

TOOLKITS = [
    "TKernel", "TKMath", "TKG2d", "TKG3d", "TKGeomBase", "TKBRep", "TKGeomAlgo",
    "TKTopAlgo", "TKPrim", "TKBO", "TKBool", "TKShHealing", "TKMesh", "TKXSBase",
    "TKSTEPBase", "TKSTEPAttr", "TKSTEP209", "TKSTEP", "TKIGES", "TKCDF", "TKLCAF",
    "TKCAF", "TKXCAF", "TKXDESTEP", "TKXDEIGES",
]

# Packages that are listed in a toolkit's PACKAGES file but must not be built
# (they need the visualisation toolkits TKV3d/TKService/TKVCAF).
SKIP_PACKAGES = {"XCAFPrs"}

# Individual source files to skip (basename). Windows/Mac-only files are also
# filtered by the patterns below.
SKIP_FILES = {
    "STEPCAFControl_Writer.cxx",  # needs XCAFPrs (TKV3d); only the reader is used
    "OSD_Parallel_TBB.cxx",       # TBB backend, HAVE_TBB is not defined
}
SKIP_PATTERNS = ("_WNT.cxx", "_wnt.cxx", "Win32", "_mac", "Cocoa", "_osx", "WNT_", "_WIN32")

# Extra sources from toolkits that are NOT built as a whole but of which a few
# objects are needed by XCAF (TKV3d/TKService).  Kept empty unless the link
# reports undefined symbols; see README.md.
EXTRA_SOURCES = [
]

COMMON_FLAGS = ("-std=c++17 -O2 -fPIC -DNDEBUG -DOCC_CONVERT_SIGNALS -DHAVE_FREEIMAGE=0 -DU3DCONV_NO_GRAPHIC3D -w")
C_FLAGS = ("-O2 -fPIC -DNDEBUG -w")


def package_sources(src, pkg):
    pdir = os.path.join(src, pkg)
    files_list = os.path.join(pdir, "FILES")
    if os.path.exists(files_list):
        names = [l.strip() for l in open(files_list) if l.strip()]
        names = [n for n in names if n.endswith(".cxx") or n.endswith(".cpp") or n.endswith(".c")]
    else:
        names = sorted(os.path.basename(p) for p in glob.glob(os.path.join(pdir, "*.cxx")) + glob.glob(os.path.join(pdir, "*.cpp")))
    out = []
    for n in names:
        if n in SKIP_FILES:
            continue
        if any(p in n for p in SKIP_PATTERNS):
            continue
        if not os.path.exists(os.path.join(pdir, n)):
            print("warning: %s listed in %s/FILES does not exist" % (n, pkg), file=sys.stderr)
            continue
        out.append(os.path.join(pdir, n))
    return out


def esc(s):
    return s.replace("$", "$$").replace(" ", "$ ").replace(":", "$:")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True)
    ap.add_argument("--build", required=True)
    ap.add_argument("--inc", required=True)
    ap.add_argument("--cxx", required=True)
    ap.add_argument("--ar", required=True)
    ap.add_argument("--main", required=True, help="directory containing main.cpp")
    ap.add_argument("--target", default="x86_64")
    ap.add_argument("--out", required=True, help="final executable path")
    ap.add_argument("--extra-cxxflags", default="")
    ap.add_argument("--extra-ldflags", default="")
    a = ap.parse_args()

    src = os.path.abspath(a.src)
    build = os.path.abspath(a.build)
    os.makedirs(build, exist_ok=True)

    arch_flags = ""
    if a.target.startswith("aarch64"):
        arch_flags = "-mcpu=generic"

    lines = []
    w = lines.append
    w("# generated by gen_ninja.py -- do not edit")
    w("ninja_required_version = 1.5")
    w("cxx = %s" % a.cxx)
    w("ar = %s" % a.ar)
    w("cxxflags = %s %s %s -I%s" % (COMMON_FLAGS, arch_flags, a.extra_cxxflags, a.inc))
    w("cflags = %s %s -I%s" % (C_FLAGS, arch_flags, a.inc))
    w("ldflags = -static -s %s" % a.extra_ldflags)
    w("")
    w("rule cxx")
    w("  command = $cxx $cxxflags -MMD -MF $out.d -c $in -o $out")
    w("  depfile = $out.d")
    w("  deps = gcc")
    w("  description = CXX $out")
    w("")
    w("rule cc")
    w("  command = $cxx -x c $cflags -MMD -MF $out.d -c $in -o $out")
    w("  depfile = $out.d")
    w("  deps = gcc")
    w("  description = CC $out")
    w("")
    w("rule ar")
    w("  command = rm -f $out && $ar rcs $out $in")
    w("  description = AR $out")
    w("")
    w("rule link")
    w("  command = $cxx $ldflags -o $out $in_main -Wl,--start-group $libs -Wl,--end-group -lpthread")
    w("  description = LINK $out")
    w("")

    libs = []
    nfiles = 0
    for tk in TOOLKITS:
        pkgs = [l.strip() for l in open(os.path.join(src, tk, "PACKAGES")) if l.strip()]
        objs = []
        for pkg in pkgs:
            if pkg in SKIP_PACKAGES:
                continue
            for s in package_sources(src, pkg):
                rel = os.path.relpath(s, src)
                obj = os.path.join("obj", os.path.splitext(rel)[0] + ".o")
                rule = "cc" if s.endswith(".c") else "cxx"
                w("build %s: %s %s" % (esc(obj), rule, esc(s)))
                objs.append(obj)
                nfiles += 1
        lib = "lib/lib%s.a" % tk
        w("build %s: ar %s" % (esc(lib), " ".join(esc(o) for o in objs)))
        libs.append(lib)
        w("")

    extra_objs = []
    for pkg, fn in EXTRA_SOURCES:
        s = os.path.join(src, pkg, fn)
        obj = os.path.join("obj", pkg, os.path.splitext(fn)[0] + ".o")
        w("build %s: cxx %s" % (esc(obj), esc(s)))
        extra_objs.append(obj)
        nfiles += 1
    if extra_objs:
        w("build lib/libTKExtra.a: ar %s" % " ".join(esc(o) for o in extra_objs))
        libs.append("lib/libTKExtra.a")
        w("")

    main_dir = os.path.abspath(a.main)
    main_objs = []
    for s in sorted(glob.glob(os.path.join(main_dir, "*.cpp"))):
        obj = os.path.join("obj", "u3dconv", os.path.splitext(os.path.basename(s))[0] + ".o")
        w("build %s: cxx %s" % (esc(obj), esc(s)))
        w("  cxxflags = $cxxflags -I%s" % main_dir)
        main_objs.append(obj)

    out = os.path.abspath(a.out)
    w("build %s: link %s | %s" % (esc(out), " ".join(esc(o) for o in main_objs), " ".join(libs)))
    w("  in_main = %s" % " ".join(main_objs))
    w("  libs = %s" % " ".join(libs))
    w("")
    w("build all: phony %s" % esc(out))
    w("default all")

    with open(os.path.join(build, "build.ninja"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d OCCT sources, %d toolkits, target %s)" % (
        os.path.join(build, "build.ninja"), nfiles, len(TOOLKITS), a.target))


if __name__ == "__main__":
    main()
